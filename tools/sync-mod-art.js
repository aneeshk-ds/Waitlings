#!/usr/bin/env node
/*
 * Writes the app mod's artwork file from the browser extension's sources, so
 * both products draw the same companions and activity icons.
 *
 *   node tools/sync-mod-art.js            writes mod/hooks/art.ts
 *   node tools/sync-mod-art.js <path>     writes to <path>
 *
 * Run it after changing src/core/themes.js, activities.js or defaults.js.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
globalThis.chrome = {};
for (const file of ['defaults', 'themes', 'activities']) require(path.join(root, 'src/core', file + '.js'));
const W = globalThis.Waitlings;

const xml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// A text companion becomes an SVG whose frames take turns, so the app can
// animate it without redrawing. The grey reads on light and dark backgrounds.
const FONT_PX = 14;
const LINE_PX = 20;
function textToSvg(theme) {
  const n = theme.frames.length;
  const total = (n * theme.interval) / 1000;
  const width = Math.ceil(theme.width * FONT_PX);
  const css =
    `.f{opacity:0;animation:k ${total}s steps(1,end) infinite}` +
    `@keyframes k{0%{opacity:1}${(100 / n).toFixed(3)}%{opacity:0}}`;
  const frames = theme.frames
    .map(
      (frame, i) =>
        `<text class="f" style="animation-delay:${(i * theme.interval) / 1000}s" x="0" y="15" ` +
        `font-family="system-ui,-apple-system,'Segoe UI',sans-serif" font-size="${FONT_PX}" fill="#7f7f95" xml:space="preserve">${xml(frame)}</text>`
    )
    .join('');
  return {
    svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${LINE_PX}"><style>${css}</style>${frames}</svg>`,
    aspect: width / LINE_PX,
    scale: 0.72, // drawn shorter than an icon, at about text height
  };
}

const companions = W.themes.map((t) => {
  const drawn = t.type === 'text' ? textToSvg(t) : { svg: t.svg, aspect: 1, scale: 1 };
  return { id: t.id, name: t.name, pack: t.pack, ...drawn };
});

const activities = W.activities.map((a) => ({
  id: a.id,
  name: a.name,
  words: a.match.source,
  svg: a.svg,
  aspect: 1,
  scale: 1,
}));

const out =
  `// Generated by tools/sync-mod-art.js from the browser extension's sources.\n` +
  `// Do not edit by hand: change src/core/*.js and run the script again.\n\n` +
  `export type Art = { id: string; name: string; svg: string; aspect: number; scale: number }\n` +
  `export type Companion = Art & { pack: string }\n` +
  `export type Activity = Art & { words: string }\n\n` +
  `export const PACKS: readonly { id: string; name: string }[] = ${JSON.stringify(W.packs, null, 2)}\n\n` +
  `export const COMPANIONS: readonly Companion[] = ${JSON.stringify(companions, null, 2)}\n\n` +
  `export const ACTIVITIES: readonly Activity[] = ${JSON.stringify(activities, null, 2)}\n\n` +
  `export const DEFAULT_PHRASES: readonly string[] = ${JSON.stringify(W.DEFAULT_PHRASES, null, 2)}\n`;

const target = process.argv[2] || path.join(root, 'mod/hooks/art.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${target}: ${companions.length} companions, ${activities.length} activities`);
